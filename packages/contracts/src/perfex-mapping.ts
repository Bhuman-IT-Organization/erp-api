/**
 * The write direction — clean name -> Perfex code. **Derived from `PERFEX_TO_CLEAN`, never
 * hand-written**: `v1/identity` writes Perfex-format rows with it (ADR-0033 decision 10), and a
 * second table would drift from the first. The forward table is one-to-one, so the inverse is total.
 */
export const PERFEX_BY_CLEAN: Readonly<Record<PermissionCode, string>> = Object.freeze(
  Object.fromEntries(Object.entries(PERFEX_TO_CLEAN).map(([perfex, clean]) => [clean, perfex])),
);

/**
 * Both helpers below look their key up with `Object.hasOwn`, never with `MAP[key] ?? null` (CR
 * review BL-1). Both maps are plain objects — an object literal and an `Object.fromEntries` — so
 * they inherit `Object.prototype`, and `MAP['constructor']`, `MAP['__proto__']`,
 * `MAP['toString']` and `MAP['hasOwnProperty']` all answer with an inherited value rather than
 * `undefined`. `?? null` then never fires and the caller receives a function or a prototype where
 * its type says `string | null`: `identity.service.ts`'s `perfexRowsFor` called `.lastIndexOf` on
 * it and raised a `TypeError` — a 500 `ERP-INTERNAL-0001` on a route whose `@ApiZod` declares
 * 422 `ERP-IDENTITY-0003`. An own-property check is the fix that keeps the exported types as they
 * are; `__tests__/perfex-mapping.spec.ts` carries a case per prototype key for both directions.
 */

/**
 * The one translation point's helper. An unmapped Perfex code returns null; the enricher decides
 * what that means — this function never invents a clean name.
 */
export function toCleanPermission(perfexCode: string): PermissionCode | null {
  return Object.hasOwn(PERFEX_TO_CLEAN, perfexCode) ? (PERFEX_TO_CLEAN[perfexCode] ?? null) : null;
}

/**
 * The write direction's helper. An unknown clean name returns null; the caller refuses to write a
 * row rather than inventing a Perfex code.
 */
export function toPerfexPermission(clean: string): string | null {
  return Object.hasOwn(PERFEX_BY_CLEAN, clean) ? (PERFEX_BY_CLEAN[clean] ?? null) : null;
}

