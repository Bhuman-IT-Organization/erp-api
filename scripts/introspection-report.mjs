// Deterministic report over prisma/schema.prisma: counts, @@ignore list, register gaps.
// No dependencies, no timestamps, sorted output, LF endings. Never reads DATABASE_URL.
// Writes prisma/model-table-map.json and prisma/INTROSPECTION.md; preserves the two
// hand-measured cost lines of an existing INTROSPECTION.md.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const schemaPath = join(root, 'prisma', 'schema.prisma');
const ownershipPath = join(root, 'prisma', 'ownership.json');
const ownershipNodePath = join(root, 'prisma', 'ownership-node.json');
const mapPath = join(root, 'prisma', 'model-table-map.json');
const reportPath = join(root, 'prisma', 'INTROSPECTION.md');

const schema = readFileSync(schemaPath, 'utf8').replace(/\r\n/g, '\n');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const prismaVersion = pkg.devDependencies?.prisma ?? '<unpinned>';
const register = JSON.parse(readFileSync(ownershipPath, 'utf8'));
if (!Array.isArray(register)) throw new Error('prisma/ownership.json must be an array');
// ADR-0035: tables the new system creates live in a second register, because the legacy register
// (prisma/ownership.json) holds only tables of the legacy schema dump. The register-gap arithmetic counts both files, or a Node-created table would be
// reported as missing from the register for ever.
const registerNode = JSON.parse(readFileSync(ownershipNodePath, 'utf8'));
if (!Array.isArray(registerNode)) throw new Error('prisma/ownership-node.json must be an array');

const byLocale = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

// Parse top-level blocks. `db pull` output is always `model X {` ... `}` at column 0.
const models = [];
let enums = 0;
const lines = schema.split('\n');
for (let i = 0; i < lines.length; i += 1) {
  const head = /^(model|enum)\s+(\S+)\s*\{/.exec(lines[i]);
  if (!head) continue;
  const [, kind, name] = head;
  let j = i + 1;
  const body = [];
  while (j < lines.length && lines[j] !== '}') {
    body.push(lines[j]);
    j += 1;
  }
  i = j;
  if (kind === 'enum') {
    enums += 1;
    continue;
  }
  let table = name;
  let ignored = false;
  for (const line of body) {
    const map = /^\s*@@map\("([^"]+)"\)/.exec(line);
    if (map) table = map[1];
    if (/^\s*@@ignore\b/.test(line)) ignored = true;
  }
  models.push({ model: name, table, ignored });
}
models.sort((a, b) => byLocale(a.model, b.model));

/**
 * Tables that exist only on a developer's machine and are therefore not a register gap.
 * `_local_import` is the completed-import marker (dump sha256 + table count) written by
 * `erp-infra/legacy-local/setup.mjs`; it is in no environment's schema and in no
 * client dump, so counting it as "missing from the register" would be reporting our own tooling.
 * A table belongs here only when it can never exist outside a local stack — a Node-created table
 * is registered in `ownership-node.json` instead (ADR-0035).
 */
const LOCAL_ONLY_TABLES = new Set(['_local_import']);

const schemaTables = new Set(models.map((m) => m.table).filter((t) => !LOCAL_ONLY_TABLES.has(t)));
const registerTables = new Set(register.map((r) => r.table));
const nodeTables = new Set(registerNode.map((r) => r.table));
const knownTables = new Set([...registerTables, ...nodeTables]);
const ignored = models.filter((m) => m.ignored);
const mapped = models.filter((m) => m.table !== m.model);
const tablesNotInOwnership = [...schemaTables].filter((t) => !knownTables.has(t)).sort(byLocale);
const ownershipNotInSchema = [...knownTables].filter((t) => !schemaTables.has(t)).sort(byLocale);
const nodeCreated = [...nodeTables].sort(byLocale);

// model-table-map.json: only models whose table differs from the model name.
const map = Object.fromEntries(mapped.map((m) => [m.model, m.table]));
writeFileSync(mapPath, JSON.stringify(map, null, 2) + '\n');

// Cost lines: the only hand-edited content; keep them if present.
let generateLine = '- prisma generate: <unmeasured>';
let tscLine = '- tsc --noEmit: <unmeasured>';
if (existsSync(reportPath)) {
  for (const line of readFileSync(reportPath, 'utf8').replace(/\r\n/g, '\n').split('\n')) {
    if (line.startsWith('- prisma generate:')) generateLine = line;
    if (line.startsWith('- tsc --noEmit:')) tscLine = line;
  }
}

const list = (items) => (items.length === 0 ? 'none' : items.map((x) => `- \`${x}\``).join('\n'));

const out = `# Introspection of the legacy database (read-only mirror)

Source: the LOCAL legacy stack at 127.0.0.1:33061 (\`erp-infra/legacy-local\`), database as configured there. The client's server is never contacted. Refresh with \`corepack yarn db:pull\` while that stack is running.

This file and \`model-table-map.json\` are generated by \`scripts/introspection-report.mjs\` (\`corepack yarn db:report\`); only the two lines under "Cost" are measured and written by hand.

| Measure | Value |
|---|---|
| Prisma version | ${prismaVersion} |
| Models | ${models.length} |
| Models with @@ignore (no primary key or unique index — Prisma Client cannot address them) | ${ignored.length} |
| Models with @@map | ${mapped.length} |
| Enums | ${enums} |
| Register records (prisma/ownership.json) | ${register.length} |
| Node-created records (prisma/ownership-node.json) | ${registerNode.length} |
| Schema tables missing from the register | ${tablesNotInOwnership.length} |
| Register tables missing from the schema | ${ownershipNotInSchema.length} |

## Tables Prisma ignores

${ignored.length === 0 ? 'none' : ignored.map((m) => `- \`${m.model}\` (table \`${m.table}\`)`).join('\n')}

## Node-created tables

Tables the new system created rather than inherited. They are owned in \`prisma/ownership-node.json\`, never in the legacy register \`prisma/ownership.json\`, which holds only tables of the legacy schema dump (ADR-0035). Their DDL is \`prisma/sql/\`, applied by \`corepack yarn db:apply\` (ADR-0036).

${nodeCreated.length === 0 ? 'none' : nodeCreated.map((t) => `- \`${t}\``).join('\n')}

## Schema tables not in ownership.json

${list(tablesNotInOwnership)}

These must be added to \`ownership.json\` here, by hand, with the owner the evidence names. A table the new system created belongs in \`ownership-node.json\` instead and is listed above, not here.

## Register tables not in the schema

${list(ownershipNotInSchema)}

## Known imperfections

- the mirror is committed as \`db pull\` + \`prisma format\` wrote it; no model is hand-edited
- reserved-word or invalid identifiers appear as \`@map\`/\`@@map\`
- mixed collations and zero-date defaults are carried verbatim as \`@db.*\` attributes and \`dbgenerated()\` defaults
- views are not introspected

## Cost

${generateLine}
${tscLine}
`;
writeFileSync(reportPath, out);
console.log(
  `models=${models.length} ignored=${ignored.length} mapped=${mapped.length} enums=${enums} ` +
    `register=${register.length} registerNode=${registerNode.length} ` +
    `missingFromRegister=${tablesNotInOwnership.length} ` +
    `missingFromSchema=${ownershipNotInSchema.length}`,
);
