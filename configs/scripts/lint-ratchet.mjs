// `corepack yarn check:ratchet`: the pinned total of suppressed lint violations (01-typescript-and-lint
// TS-18). Consumers hold identical
// copies and run it from their root.
//
// ESLint's bulk suppressions (eslint-suppressions.json) tighten themselves: a fixed violation leaves an unused
// entry and `eslint` fails until `corepack yarn lint:prune` removes it. The one hole is `eslint --suppress-all`,
// which grows the file. This script closes it: the total of every suppressed count (plus one per known
// dependency-cruiser no-circular entry) must equal `--expect <n>`. Above the pin means a suppression was
// added and is refused; below it is slack and is refused too, naming the number to lower the pin to. The number
// lives in the consumer's package.json and only ever goes down; this script never raises it.
//
// REFACTOR-BACKLOG.md is generated from the same rows and compared in memory, so a hand edit fails and `check`
// never dirties the tree. `--write` regenerates it.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const SUPPRESSIONS = 'eslint-suppressions.json';
const CYCLES = '.dependency-cruiser-known-violations.json';
const BACKLOG = 'REFACTOR-BACKLOG.md';

/** Codepoint order, as every artifact uses; never localeCompare. */
const byString = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

function parseExpect(raw) {
  const n = Number(raw);
  if (raw === undefined || String(raw).trim() === '' || !Number.isInteger(n) || n < 0) {
    throw new Error(`--expect must be a non-negative integer, got: ${raw}`);
  }
  return n;
}

const readJson = (file, fallback) =>
  existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : fallback;

function collectRows() {
  const rows = [];
  for (const [file, rules] of Object.entries(readJson(SUPPRESSIONS, {}))) {
    for (const [rule, { count }] of Object.entries(rules)) rows.push({ file, rule, count });
  }
  for (const entry of readJson(CYCLES, [])) {
    if (entry.rule?.name === 'no-circular') {
      rows.push({ file: entry.from, rule: 'no-circular', count: 1 });
    }
  }
  return rows.sort((a, b) => byString(a.file, b.file) || byString(a.rule, b.rule));
}

function renderBacklog(name, total, rows) {
  return [
    '<!-- Generated by corepack yarn check:ratchet --write from eslint-suppressions.json and .dependency-cruiser-known-violations.json. Never edit by hand (01-typescript-and-lint TS-18). -->',
    '',
    `# Refactor backlog: ${name}`,
    '',
    `${total} violations of the Phase 4 rules existed when those rules were switched on. Work them down beside feature work: fix one, run \`corepack yarn lint:prune\`, then \`corepack yarn check:ratchet --write\`, and lower \`--expect\` in \`package.json\` to the new total in the same commit.`,
    '',
    '| Repository | File | Rule | Count |',
    '|---|---|---|---|',
    ...rows.map((r) => `| ${name} | ${r.file} | ${r.rule} | ${r.count} |`),
    '',
  ].join('\n');
}

function main(args) {
  const at = args.indexOf('--expect');
  const expected = parseExpect(at === -1 ? undefined : args[at + 1]);
  const rows = collectRows();
  const total = rows.reduce((sum, r) => sum + r.count, 0);
  const backlog = renderBacklog(readJson('package.json', {}).name, total, rows);
  if (args.includes('--write')) writeFileSync(BACKLOG, backlog);

  const failures = [];
  if (!existsSync(BACKLOG) || readFileSync(BACKLOG, 'utf8') !== backlog) {
    failures.push(
      `${BACKLOG} is not what the suppressions generate; run corepack yarn check:ratchet --write and commit it`,
    );
  }
  if (total > expected) {
    failures.push(
      `${total} suppressed violation(s) exceed the pinned ${expected}: a suppression was added; fix the code, or justify one line with an eslint-disable -- reason (TS-18)`,
    );
  }
  if (total < expected) {
    failures.push(
      `pinned ${expected} but ${total} remain; lower --expect in package.json to ${total} (the ratchet only goes down)`,
    );
  }
  return { total, expected, failures };
}

try {
  const { total, expected, failures } = main(process.argv.slice(2));
  for (const failure of failures) process.stderr.write(`lint-ratchet: ${failure}\n`);
  if (failures.length > 0) process.exit(1);
  process.stdout.write(
    `lint-ratchet: ${total} suppressed violation(s), pinned ${expected}; ${BACKLOG} current\n`,
  );
} catch (err) {
  process.stderr.write(`lint-ratchet: ${err.message}\n`);
  process.exit(1);
}
